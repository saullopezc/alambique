#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
#
# guard-autoria-docs.sh — Vigila la autoría de documentos y de código fuente (R-11).
#
# QUÉ VIGILA: el fichero que el agente acaba de escribir con las herramientas
# de edición del harness. Tres reglas que se olvidan con facilidad, cada una
# con su alcance:
#   1. ATRIBUCIÓN A IA: ninguna IA figura como autor, analista, editor ni
#      revisor. De cada artefacto responde una persona identificada (R-11); una
#      IA es una herramienta, como el teclado.
#      ALCANCE: todo `.md`, esté donde esté, y los ficheros con estas
#      extensiones, y solo estas: `.c`, `.h`, `.cpp`, `.hpp`, `.pl`, `.pm`,
#      `.php`, `.py`, `.sh`, `.java` y `.xml`, tengan o no cabecera de
#      autoría. Cualquier otro fichero (`.js`, `.go`, un `Dockerfile`) no se
#      mira. Se lee el fichero entero y se nombran las líneas que casan, hasta
#      cinco: una línea ambigua arriba no tapa una atribución real más abajo.
#   2. FIRMA: los documentos de proyecto llevan firma. Vale cualquiera de las
#      dos: la cabecera `responsable:` rellena (la que piden la norma y las
#      plantillas de documentación), o la firma al pie con el correo de la capa
#      local.
#      ALCANCE: los `.md` bajo `docs/`, `doc/`, `qa/` o `runbooks/`, y los
#      `README.md` y `CHANGELOG.md`. A un `.md` suelto en otro sitio no se le
#      pide firma.
#   3. SELLO: el código cuya cabecera lleva fecha de modificación se sella al
#      modificarlo, con un par "Modified By / Modified Date" con la fecha de hoy.
#      ALCANCE: los ficheros de esas extensiones que en sus primeras 40
#      líneas traen una línea `Author:` (o `Autor:`) Y un campo `Modified
#      Date:` (o `Fecha de modificación:`). A una cabecera con `Author` y
#      `Created Date` y nada más no se le pide sello: el guard no le inventa a
#      un fichero una convención que no trae.
# FUERA DE ALCANCE, las tres: la configuración del propio harness (<conf>), y
# lo que cuelga de un directorio `skills/` o `.config/`.
# Devuelve el aviso al modelo para que lo corrija en el mismo turno, sin
# molestar a la persona.
#
# LO QUE NO VE:
#   - Lo que no se escribe con las herramientas de edición: el hook se
#     registra para ellas. Un documento escrito por redirección de shell
#     (`cat > notas.md`) no llega aquí. Tampoco el mensaje de un commit:
#     `git commit -m ... -m "Co-Authored-By: ..."` entra sin aviso.
#   - Una atribución redactada de otra manera. Las formas y los nombres de
#     asistente que reconoce son los más corrientes: un punto de partida, que
#     puede no estar completo y que cada puesto ajusta a su caso. No casan
#     «generado por inteligencia artificial», «con ayuda de IA», «escrito por
#     un LLM», `Generated by GitHub Copilot`, `Autor: Codex` ni `Autor: Aider`.
#     Tampoco una etiqueta o un nombre unidos a otra palabra por un guion
#     bajo: `commit_author: X` no es la etiqueta `author`, ni `x_model` el
#     nombre X. El guion bajo solo cuenta pegado por fuera, como cursiva.
#     Los nombres se amplían en `modelos.conf`; las formas, tocando el patrón.
#   - Los nombres de una línea de `modelos.conf` que no vale como expresión
#     regular (`a(b`) o que casa con la línea vacía (`.*`): esa línea se
#     ignora, y se dice a la persona con su número.
# Y LO QUE VE DE MÁS:
#   - El alcance de la firma se decide sobre la RUTA COMPLETA del fichero, no
#     desde la raíz del proyecto: si el proyecto cuelga de un directorio
#     llamado `docs`, `doc`, `qa` o `runbooks`, todos sus `.md` reciben el
#     aviso de firma. Y todo `README.md` cuenta como documento de proyecto,
#     también el de `_local/`.
#   - Un nombre ambiguo que de verdad es otra cosa (`Editor: Cursor` en una
#     tabla de herramientas). Por eso el aviso da la línea y pide juzgarla.
#
# DATO DE LA CAPA LOCAL:
#   - QUIÉN firma no se escribe aquí: se lee de `negocio.conf`, en cascada. Gana
#     el `_local/negocio.conf` más cercano al fichero escrito (proyecto o
#     cliente); si no hay, <conf>/_local/negocio.conf. $ALAMBIQUE_NEGOCIO fija
#     uno y salta la cascada. La regla se publica, la identidad no.
#     $ALAMBIQUE_LOCAL cambia la capa local del puesto entera.
#   - La lista de asistentes trae los nombres más corrientes, de varios
#     proveedores: la regla dice "ninguna IA", no "ninguna IA de marca X". Se
#     amplía desde <conf>/_local/modelos.conf (o $ALAMBIQUE_MODELOS), un nombre
#     por línea; cada línea entra en el patrón como expresión regular.
#   - El aviso de atribución da los números de línea y pide juzgarlas: el patrón
#     encuentra, quien lee decide (más abajo, qué ve y qué no).
#
# CONTRATO: ninguno propio. La carga de entrada y la respuesta las habla
# `lib/hook.sh`; la comprobación se hace sobre el fichero ya escrito en disco y
# vale para cualquier harness.
#
# FALLO PROPIO: no bloquea (ver `lib/hook.sh`). Si un documento no trae
# cabecera `responsable` y tampoco hay identidad configurada lo DICE: una
# comprobación que se degrada en silencio es peor que no tenerla. Por lo mismo,
# una línea de `modelos.conf` que no sirve se ignora y se dice, en vez de
# dejar que apague la detección.
#
# Author       : Saul López
# Created Date : 2026-08-24

set -uo pipefail
GUARD="guard-autoria-docs"
_lib="$(cd "$(dirname "$0")" 2>/dev/null && pwd)/lib/hook.sh"
if [ ! -r "$_lib" ]; then
    # La única salida que no puede delegarse: avisa de que falta el delegado.
    printf '{"systemMessage":"%s: falta lib/hook.sh — el control NO está actuando"}\n' "$GUARD"
    exit 0
fi
# shellcheck source=lib/hook.sh
. "$_lib"

CONF="$(hook_conf)"
LOCAL_PUESTO="${ALAMBIQUE_LOCAL:-$CONF/_local}"

hook_leer
f="$(hook_fichero)"
[ -n "$f" ] && [ -f "$f" ] || exit 0

# La configuración del propio harness y las skills no son documentos de proyecto.
case "$f" in
    "$CONF"/*|*/skills/*|*/.config/*) exit 0 ;;
esac

avisos=""

# --- Identidad de quien firma: dato local, no regla --------------------------
# Se resuelve en cascada, como los alias: gana el `_local/negocio.conf` más
# cercano al fichero escrito —el del proyecto, o el de su cliente— y, si no hay
# ninguno, el del puesto. Así un puesto firma con una identidad o con varias.
# $ALAMBIQUE_NEGOCIO fija una y salta la cascada.
# Se lee con grep, nunca con `source`: un fichero de datos no ejecuta nada.
NEGOCIO="${ALAMBIQUE_NEGOCIO:-}"
if [ -z "$NEGOCIO" ]; then
    d="$(cd "$(dirname "$f")" 2>/dev/null && pwd)"
    while [ -n "$d" ] && [ "$d" != "/" ] && [ "$d" != "${HOME:-}" ]; do
        if [ -r "$d/_local/negocio.conf" ]; then NEGOCIO="$d/_local/negocio.conf"; break; fi
        d="$(dirname "$d")"
    done
    [ -n "$NEGOCIO" ] || NEGOCIO="$LOCAL_PUESTO/negocio.conf"
fi
dato() { grep -m1 "^$1=" "$NEGOCIO" 2>/dev/null | cut -d= -f2-; }
CORREO="$(dato autor_correo)"
FIRMA="$(dato firma_doc)"

# --- Nombres de asistente conocidos (dato) -----------------------------------
# Dos clases, porque no pesan igual. Los INEQUÍVOCOS solo nombran a un
# asistente. Los AMBIGUOS son además una palabra corriente o un nombre de
# persona, y solo cuentan cuando ocupan ellos solos el sitio del autor.
# Lo que añade modelos.conf entra como inequívoco: lo declaró el puesto.
IA_CLAROS='claude|anthropic|chatgpt|gpt-?[0-9][a-z0-9.]*|openai|copilot|gemini|deepseek|codeium|(un )?asistente de ia|(an )?ai assistant'
IA_AMBIGUOS='bard|llama|mistral|cursor|devin|grok|(una )?ia|(an )?ai'
MODELOS_CONF="${ALAMBIQUE_MODELOS:-$LOCAL_PUESTO/modelos.conf}"
if [ -r "$MODELOS_CONF" ]; then
    # Cada línea entra en el patrón como expresión regular. Una que grep
    # rechaza apagaría la detección entera, y una que casa con la línea vacía
    # marcaría a cualquier autor: se ignoran las dos, y se dice.
    extra=""; malas=""; n=0
    # `|| [ -n "$l" ]`: la última línea cuenta aunque no acabe en salto.
    while IFS= read -r l || [ -n "$l" ]; do
        n=$((n + 1))
        l="${l%$'\r'}"
        l="${l#"${l%%[![:space:]]*}"}"; l="${l%"${l##*[![:space:]]}"}"
        case "$l" in ''|\#*) continue ;; esac
        grep -qiE -- "($l)" <<< "" 2>/dev/null
        if [ $? -ne 1 ]; then malas="${malas:+$malas, }$n"; continue; fi
        extra="${extra:+$extra|}$l"
    done < "$MODELOS_CONF"
    [ -n "$extra" ] && IA_CLAROS="$IA_CLAROS|$extra"
    [ -n "$malas" ] && hook_avisar "$GUARD: en $MODELOS_CONF se ignoran las líneas $malas: no son una expresión regular válida, o casan con cualquier nombre. Esos nombres NO se están vigilando."
fi

# --- Cómo se reconoce una atribución -----------------------------------------
# Tres formas:
#   etiqueta    `Autor: X`, `**Autor**: X`, `| Autor | X |`, `Modified By : X`,
#               `@author X`. Un inequívoco vale en cualquier punto del valor
#               (`Autor: Ana Ruiz y X`); un ambiguo, solo si es el valor entero.
#   participio  `Generado con X`, `Generado automáticamente por X`,
#               `Generated with [X]`, `Co-Authored-By: X`. El nombre va justo
#               detrás de la preposición; un ambiguo, además, cerrando la frase.
#   genérica    la forma inglesa con guion, abriendo la línea.
# Entre la palabra clave y el nombre va `.`, NUNCA `[^\n]`: dentro de corchetes
# la barra invertida es literal, y `[^\n]` excluye la letra "n" — con eso
# "Generado con <asistente>" pasaba sin aviso. grep ya trabaja línea a línea.
# Una atribución redactada de otra manera no casa, y un ambiguo puede ser de
# verdad otra cosa (`Editor: Cursor` en una tabla de herramientas): por eso el
# aviso da la línea y pide juzgarla, no borrarla. El detalle, en la cabecera.
# El guion bajo cuenta como marca de cursiva solo PEGADO por fuera a la
# palabra clave o al nombre (`_Generado con X_`, `_Autor_: X`, `Autor: _X_`):
# por eso va como `_*` a cada lado y no dentro de la frontera. Uniendo dos
# palabras es un identificador, y ahí no casa: ni `text_editor:` es la
# etiqueta `editor:`, ni `claude_model` es el nombre de un asistente.
_ini='(^|[^[:alnum:]_])_*'
_marca='[]*_`[[:space:]]*'      # negrita, cursiva, código, corchete de enlace
_etq='((co-?)?autor(a|es|as|ía|ia)?|authors?|analista|editor(a|es)?|revisor(a|es)?|responsable|elaborado por|modified by)'
_campo="(${_etq}${_marca}[:=|]${_marca}|@author[[:space:]]+)"
_part='(generad[oa]s?|generated|elaborad[oa]|redactad[oa]|escrit[oa]|written|cread[oa]|created|revisad[oa]|reviewed|hech[oa]|made|asistid[oa]|assisted|(co-)?authored)'
_adv='([[:space:]]+[^[:space:]]+(mente|ly))?'
_prep='[[:space:]-]+(por|con|mediante|usando|by|with|using)[[:space:]]*[:=]?'
_ayuda='((la |el |the )?(ayuda|asistencia|apoyo|asistente|herramienta|help|assistance|tool)( de| del| of| from)?[[:space:]]+)?'
_fin='[]*_`)]*([[:space:]]*$|[.,;:!?]([[:space:]]|$)|[[:space:]]*[|<(])'
IA_P1="${_ini}${_campo}.{0,40}\\b_*(${IA_CLAROS})_*\\b"
IA_P2="${_ini}${_campo}(${IA_AMBIGUOS})${_fin}"
IA_P3="${_ini}${_part}${_adv}${_prep}${_marca}${_ayuda}${_marca}(${IA_CLAROS})_*\\b"
IA_P4="${_ini}${_part}${_adv}${_prep}${_marca}(${IA_AMBIGUOS})${_fin}"
IA_P5='^[^[:alnum:]]*ai[- ](generated|written|assisted)\b'
# Todas las líneas que parecen una atribución, y no solo la primera: una
# ambigua que resulta ser otra cosa (`| Editor | Cursor |`) taparía la real que
# venga después. Se nombran hasta cinco y se dice cuántas quedan.
ia_lineas() {
    grep -niE -e "$IA_P1" -e "$IA_P2" -e "$IA_P3" -e "$IA_P4" -e "$IA_P5" "$1" 2>/dev/null | cut -d: -f1 | \
        awk 'NR <= 5 { l = l (NR > 1 ? ", " : "") $1 } END { if (NR > 5) l = l " y " (NR - 5) " más"; if (NR) print NR ":" l }'
}
aviso_ia() { # <cuántas>:<líneas>
    if [ "${1%%:*}" = 1 ]; then
        printf 'La línea %s parece una atribución a IA: si lo es, retirarla — una IA es una herramienta, nunca autor, analista ni revisor (R-11). Si la línea habla de otra cosa, no tocarla.' "${1#*:}"
    else
        printf 'Las líneas %s parecen, cada una, una atribución a IA: la que lo sea, retirarla — una IA es una herramienta, nunca autor, analista ni revisor (R-11). La que hable de otra cosa, no tocarla.' "${1#*:}"
    fi
}

# Cabecera YAML con `responsable:` relleno. No cuenta el valor vacío, ni un
# marcador `<...>`, ni un pendiente (`TODO`), con o sin comillas.
# Sin tubería: con `pipefail`, un `awk` que sale pronto mataría al productor.
tiene_responsable() {
    awk '{ sub(/\r$/, "") }
         NR == 1 { if ($0 != "---") exit; next }
         $0 == "---" || NR > 40 { exit }
         /^responsable:/ {
             v = $0
             sub(/^responsable:[[:space:]]*/, "", v); sub(/[[:space:]]+#.*$/, "", v)
             gsub(/^["\047]|["\047]$/, "", v); gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
             if (v != "" && v !~ /^[<#]/ && tolower(v) !~ /^(todo|tbd|pendiente|\?+)$/) ok = 1
             exit
         }
         END { exit ok ? 0 : 1 }' "$1" 2>/dev/null
}

case "$f" in
  *.md)
    # ---- firma: solo la documentación de proyecto ----
    if grep -qiE '(^|/)(docs?|qa|runbooks)/|(README|CHANGELOG)\.md$' <<< "$f"; then
        if tiene_responsable "$f"; then
            :   # firmado por cabecera: es la forma que piden la norma y las plantillas
        elif [ -z "$CORREO" ]; then
            avisos="El documento no declara 'responsable' en su cabecera, y no hay identidad de autoría configurada (falta ${NEGOCIO} o su clave autor_correo) para comprobar una firma al pie: la firma NO se ha comprobado."
        else
            grep -qF -- "$CORREO" "$f" 2>/dev/null || \
                avisos="El documento no lleva firma. Declarar 'clasificacion' y 'responsable' en su cabecera, o añadir al pie: ${FIRMA:-la firma indicada en $NEGOCIO}."
        fi
    fi
    ;;

  *.c|*.h|*.cpp|*.hpp|*.pl|*.pm|*.php|*.py|*.sh|*.java|*.xml)
    # ---- sello: solo si la cabecera YA lleva autoría y fecha de modificación ----
    cab="$(head -n 40 "$f")"
    if grep -qiE '^[^A-Za-z0-9]*(Author|Autor)[[:space:]]*:' <<< "$cab" \
       && grep -qiE '(Modified Date|Fecha de modificaci(o|ó)n)[[:space:]]*:' <<< "$cab"; then
        # Las cabeceras usan meses en inglés: forzar el locale C.
        hoy_a="$(LC_TIME=C date '+%-d %b %Y')"   # 4 Aug 2026
        hoy_b="$(LC_TIME=C date '+%d %b %Y')"    # 04 Aug 2026
        hoy_c="$(LC_TIME=C date '+%B %-d %Y')"   # August 4 2026
        hoy_d="$(date '+%Y-%m-%d')"              # 2026-08-04
        if ! grep -qF -e "$hoy_a" -e "$hoy_b" -e "$hoy_c" -e "$hoy_d" <<< "$cab"; then
            avisos="El fichero tiene cabecera de autoría con fecha y hoy se modificó, pero no se selló. Añadir un par nuevo tras el último: 'Modified By   : $(dato autor_nombre)' / 'Modified Date : ${hoy_a}' (respetar el estilo de comentario y el formato de fecha del propio fichero; si el par existente está vacío, rellenarlo en lugar de añadir otro)."
        fi
    fi
    ;;

  *) exit 0 ;;
esac

# ---- atribución a IA: todo `.md` y las extensiones de arriba, con cabecera o sin ella ----
# Se mira el fichero entero, no solo la cabecera: la atribución también se
# deja en un comentario a mitad de fichero, o al pie.
ln="$(ia_lineas "$f")"; [ -n "$ln" ] && avisos="${avisos:+$avisos }$(aviso_ia "$ln")"

[ -z "$avisos" ] && exit 0
hook_contexto "AUTORIA [$f]: $avisos"
